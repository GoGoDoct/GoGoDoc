_SGGU_BY_SIDO: dict[str, dict[str, str]] = {
    "110000": _SEOUL_SGGU,
    "410000": _GYEONGGI_SGGU,
}


def location_to_codes(location: str) -> tuple[str, str]:
    """거주지 텍스트 → (sidoCd, sgguCd)

    매핑 실패 시 빈 문자열 반환 (호출자가 폴백 처리)
    """
    sido_cd = ""
    for keyword, code in _SIDO_CODES.items():
        if keyword in location:
            sido_cd = code
            break

    if not sido_cd:
        return "", ""

    sggu_dict = _SGGU_BY_SIDO.get(sido_cd, {})
    sggu_cd = ""
    for name, code in sggu_dict.items():
        if name in location:
            sggu_cd = code
            break

    return sido_cd, sggu_cd
